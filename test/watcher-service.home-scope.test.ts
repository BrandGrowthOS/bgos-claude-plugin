const LEGACY_PLIST_PATH = (who: Home) => `${who.home}/Library/LaunchAgents/ai.bgos.watcher.plist`

/** Seed the owner's 0.69.x watcher: its registration (running) and the files that version left. */
function seedLegacy(platform: Platform, h: FakeServiceHost, fs: MemoryFs, who: Home) {
  if (platform === 'win32') {
    fs.writeFile(`${who.bundleDir}\\install-task.ps1`, LEGACY_PS1_HEAD(who.bundleDir))
    h.seed.task('HOAI Watcher', `${who.bundleDir}\\run-hidden.vbs`)
  } else if (platform === 'darwin') {
    h.seed.launchd(LEGACY_PLIST_PATH(who), legacyPlist(who))
  } else {
    h.seed.unit('bgos-watcher', legacyUnit(who))
  }
}

/** Everything the fake host holds that belongs to one bundle dir, in a comparable form. */
function stateOf(h: FakeServiceHost, fs: MemoryFs, who: Home) {
  const regs = (h.registrations()[k(who.bundleDir)] ?? []).slice().sort()
  const tasks = [...h.tasks].filter(([, t]) => t.action.toLowerCase().includes(k(who.bundleDir))).sort()
  const jobs = [...h.launchd].filter(([, j]) => j.content.includes(who.bundleDir)).sort()
  const units = [...h.enabled].filter((u) => (fs.readFile(`${OWNER.linux.home}/.config/systemd/user/${u}.service`) ?? '').includes(who.bundleDir)).sort()
  return { regs, tasks, jobs, units, running: h.running()[k(who.bundleDir)] ?? 0, starts: h.startsOf(who.bundleDir) }
}

// -- the HOME id --------------------------------------------------------------------------------

test('watcherHomeId: 8 lowercase hex chars, stable for one HOME however it is spelled, different for another HOME', () => {
  const id = service.watcherHomeId('C:\\Users\\kc', 'win32')
  assert.match(id, /^[0-9a-f]{8}$/)
  // Windows paths are case-insensitive and take either separator; a trailing separator is the same dir.
  for (const same of ['c:\\users\\KC', 'C:/Users/kc', 'C:\\Users\\kc\\', 'C:\\Users\\.\\kc', ' C:\\Users\\kc ']) {
    assert.equal(service.watcherHomeId(same, 'win32'), id, same)
  }
  assert.notEqual(service.watcherHomeId('E:\\rig\\scratch-home', 'win32'), id)
  const posix = service.watcherHomeId('/home/kc', 'linux')
  assert.match(posix, /^[0-9a-f]{8}$/)
  assert.equal(service.watcherHomeId('/home/kc/', 'linux'), posix)
  assert.equal(service.watcherHomeId('/home//kc', 'darwin'), posix)
  // POSIX paths are case-sensitive: another case is another HOME.
  assert.notEqual(service.watcherHomeId('/home/KC', 'linux'), posix)
  assert.notEqual(service.watcherHomeId('/tmp/rig/scratch-home', 'linux'), posix)
})

test('every service name carries home-<id>; with a namespace both compose, and no scoped name can equal an old (unscoped or namespaced) one', () => {
  for (const platform of ['win32', 'darwin', 'linux'] as const) {
    const id = service.watcherHomeId(OWNER[platform].home, platform)
    const s = spec(platform, OWNER[platform])
    const expected = { win32: `HOAI Watcher home-${id}`, darwin: `ai.bgos.watcher.home-${id}`, linux: `bgos-watcher-home-${id}` }[platform]
    assert.equal(s.label, expected, platform)
    assert.equal(s.homeId, id)
    assert.equal(s.legacy.label, { win32: 'HOAI Watcher', darwin: 'ai.bgos.watcher', linux: 'bgos-watcher' }[platform])
    const ns = watcherServiceSpec({ platform, ...OWNER[platform], env: { HOAI_SERVICE_NAMESPACE: 'stage1' }, exists: () => false })
    assert.equal(ns.label, { win32: `HOAI Watcher (stage1) home-${id}`, darwin: `ai.bgos.watcher.stage1.home-${id}`, linux: `bgos-watcher-stage1-home-${id}` }[platform])
    assert.equal(ns.legacy.label, { win32: 'HOAI Watcher (stage1)', darwin: 'ai.bgos.watcher.stage1', linux: 'bgos-watcher-stage1' }[platform])
  }
  const names = service.watcherServiceNames('', 'abcdef01')
  assert.deepEqual(names, {
    namespace: '',
    homeId: 'abcdef01',
    launchdLabel: 'ai.bgos.watcher.home-abcdef01',
    systemdUnit: 'bgos-watcher-home-abcdef01',
    taskName: 'HOAI Watcher home-abcdef01',
    runValue: 'HOAIWatcher-home-abcdef01',
  })
  // A namespace is ^[a-z0-9]{1,16}$: it can never contain the '-' a scoped suffix starts with.
  assert.equal(service.serviceNamespace({ HOAI_SERVICE_NAMESPACE: 'home-abcdef01' }), '')
})

test('the registration records its HOME: the task description and the launcher (USERPROFILE pinned before node starts), the plist and the unit', () => {
  const win = spec('win32', OWNER.win32)
  const [vbs, ps1] = win.files
  const vbsLines = vbs!.content.split('\r\n')
  const pin = vbsLines.findIndex((l) => l === 'shell.Environment("Process")("USERPROFILE") = "C:\\Users\\kc"')
  assert.ok(pin >= 0, vbs!.content)
  assert.ok(pin < vbsLines.findIndex((l) => l.startsWith('shell.Run ')), 'pinned before node starts')
  const decl = (name: string) => ps1!.content.split('\r\n').find((l) => l.startsWith(`$${name} = `))!.slice(`$${name} = `.length)
  assert.equal(evalPs(decl('description')), 'HOAI per-machine watcher, installed from home=C:\\Users\\kc')
  assert.match(ps1!.content, /Register-ScheduledTask -TaskName \$name -Description \$description /)
  assert.match(spec('darwin', OWNER.darwin).files[0]!.content, /<key>HOME<\/key><string>\/Users\/kc<\/string>/)
  assert.match(spec('linux', OWNER.linux).files[0]!.content, /^Environment=HOME=\/home\/kc$/m)
})

// -- two HOMEs side by side ----------------------------------------------------------------------

for (const platform of ['win32', 'darwin'] as const) {
  test(`${platform}: two HOMEs install side by side and neither replaces the other`, async () => {
    const { fs, h } = host(platform)
    const owner = await installWatcherService(spec(platform, OWNER[platform]), { exec: h.exec, fs, sleep })
    assert.equal(owner.ok, true, owner.message)
    const ownerBefore = stateOf(h, fs, OWNER[platform])
    assert.equal(ownerBefore.regs.length, 1)
    assert.equal(ownerBefore.running, 1)
    const scratch = await installWatcherService(spec(platform, SCRATCH[platform]), { exec: h.exec, fs, sleep })
    assert.equal(scratch.ok, true, scratch.message)
    assert.deepEqual(stateOf(h, fs, OWNER[platform]), ownerBefore, "the owner's registration and its running watcher are untouched")
    const scratchState = stateOf(h, fs, SCRATCH[platform])
    assert.equal(scratchState.regs.length, 1)
    assert.equal(scratchState.running, 1)
    assert.notDeepEqual(scratchState.regs, ownerBefore.regs)
  })
}

test('linux: a scratch HOME install never reaches the owner unit (the user manager only reads the real HOME), it fails by name instead', async () => {
  const { fs, h } = host('linux')
  const owner = await installWatcherService(spec('linux', OWNER.linux), { exec: h.exec, fs, sleep })
  assert.equal(owner.ok, true, owner.message)
  const ownerBefore = stateOf(h, fs, OWNER.linux)
  const ownerUnit = spec('linux', OWNER.linux).label
  const mark = h.calls.length
  const scratch = await installWatcherService(spec('linux', SCRATCH.linux), { exec: h.exec, fs, sleep })
  assert.equal(scratch.ok, false)
  assert.match(scratch.message, /does not exist/)
  assert.deepEqual(stateOf(h, fs, OWNER.linux), ownerBefore)
  // Reading the old name's record (show) is how ownership is decided; nothing else may name the owner's units.
  for (const call of h.calls.slice(mark)) assert.ok(!call.includes(ownerUnit) && (/ show /.test(call) || !/ bgos-watcher$/.test(call)), call)
})

// -- a scratch HOME cannot touch the default HOME's (0.69.x) watcher -------------------------

for (const platform of ['win32', 'darwin', 'linux'] as const) {
  test(`${platform}: a scratch HOME install, status and uninstall leave the owner's 0.69.x "${platform === 'win32' ? 'HOAI Watcher' : platform === 'darwin' ? 'ai.bgos.watcher' : 'bgos-watcher'}" exactly as it was, and report it`, async () => {
    const { fs, h } = host(platform)
    seedLegacy(platform, h, fs, OWNER[platform])
    // The rig's scratch bundle still holds the task script a 0.69.x install wrote there.
    if (platform === 'win32') fs.writeFile(`${SCRATCH.win32.bundleDir}\\install-task.ps1`, LEGACY_PS1_HEAD(SCRATCH.win32.bundleDir))
    const before = stateOf(h, fs, OWNER[platform])
    assert.equal(before.regs.length, 1)
    assert.equal(before.running, 1)
    const s = spec(platform, SCRATCH[platform])
    const installed = await installWatcherService(s, { exec: h.exec, fs, sleep })
    assert.deepEqual(stateOf(h, fs, OWNER[platform]), before, 'install')
    assert.equal(installed.legacy?.state, 'foreign')
    assert.match(installed.notes.join('\n'), new RegExp(`left .* alone`))
    assert.ok(installed.notes.join('\n').includes(OWNER[platform].home), installed.notes.join('\n'))
    const status = await watcherServiceStatus(s, { exec: h.exec, fs })
    assert.deepEqual(stateOf(h, fs, OWNER[platform]), before, 'status')
    assert.equal(status.legacy?.state, 'foreign')
    if (!installed.ok) assert.equal(status.active, false, "the owner's job is never reported as this HOME's")
    const removed = await uninstallWatcherService(s, { exec: h.exec, fs })
    assert.deepEqual(stateOf(h, fs, OWNER[platform]), before, 'uninstall')
    assert.equal(removed.legacy?.state, 'foreign')
    if (platform === 'darwin') assert.equal(fs.exists(LEGACY_PLIST_PATH(OWNER.darwin)), true, "the owner's plist stays")
    if (platform === 'linux') assert.equal(fs.exists(`${OWNER.linux.home}/.config/systemd/user/bgos-watcher.service`), true, "the owner's unit file stays")
  })
}

