/**
 * lib/watcher-service.mjs: the watcher's OS service is scoped to the HOME it
 * was installed from (board row dfafdfb6, mission 151 goal 8).
 *
 * The service names used to be fixed per user account: Scheduled Task
 * "HOAI Watcher" (+ HKCU Run value HOAIWatcher), launchd label ai.bgos.watcher,
 * systemd --user unit bgos-watcher. A test rig's daemon running from a scratch
 * HOME (BGOS #2432: a rig backend asked a scratch v0.69.0 daemon to install the
 * watcher; only a 409 from enroll stopped it) or any second install on the same
 * account addressed the SAME names: Register-ScheduledTask -Force, launchctl
 * bootout, systemctl restart / disable. It replaced or stopped the owner's real
 * watcher.
 *
 * Now every name carries `home-<id>`, a short hash of the normalized HOME, the
 * registration records that HOME, an install / uninstall acts only on its own
 * HOME's registration and refuses one that records another HOME, and a 0.69.x
 * registration under the old name is renamed in place when (and only when) it
 * was installed from the same HOME. One from another HOME is left alone and
 * reported.
 *
 * Every OS call goes through test/helpers/fake-service-host.ts: a faked Task
 * Scheduler + Run key, launchd domain and systemd --user manager. No real task,
 * job, unit or registry value is created, changed or read.
 *
 * Run: npx tsx --test test/watcher-service.home-scope.test.ts
 */

