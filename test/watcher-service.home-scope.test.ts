const k = (dir: string) => dir.toLowerCase()

// -- what a 0.69.x install left behind, byte for byte as that version wrote it ------------------

const LEGACY_PS1_HEAD = (bundleDir: string) =>
  [
    '# HOAI Watcher: logon task for the per-machine watcher (generated by lib/watcher-service.mjs).',
    'param([Parameter(Mandatory = $true)][ValidateSet("install", "start", "stop", "uninstall", "status")][string]$Action)',
    "$name = 'HOAI Watcher'",
    `$vbs = '${bundleDir}\\run-hidden.vbs'`,
    `$watcherScript = '${bundleDir}\\bin\\hoai-watcher.mjs'`,
    "$runKey = 'HKCU:\\Software\\Microsoft\\Windows\\CurrentVersion\\Run'",
    "$runValue = 'HOAIWatcher'",
    '',
  ].join('\r\n')

