// -- the same HOME upgrades from 0.69.x: renamed in place, no gap, never two watchers ---------

for (const platform of ['win32', 'darwin', 'linux'] as const) {
  test(`${platform}: the same HOME's 0.69.x registration is renamed in place: one registration, one watcher, the old name and its files gone`, async () => {
    const { fs, h } = host(platform)
    seedLegacy(platform, h, fs, OWNER[platform])
    const s = spec(platform, OWNER[platform])
    const result = await installWatcherService(s, { exec: h.exec, fs, sleep })
    assert.equal(result.ok, true, result.message)
    assert.equal(result.legacy?.state, 'migrated')
    const after = stateOf(h, fs, OWNER[platform])
    const regName = { win32: `task:${s.label}`, darwin: `launchd:${s.label}`, linux: `systemd:${s.label}` }[platform]
    assert.deepEqual(after.regs, [regName])
    assert.equal(after.running, 1)
    if (platform === 'win32') assert.equal(h.tasks.has('HOAI Watcher'), false)
    if (platform === 'darwin') {
      assert.equal(h.launchd.has('ai.bgos.watcher'), false)
      assert.equal(fs.exists(LEGACY_PLIST_PATH(OWNER.darwin)), false, 'the old plist would load again at the next login')
    }
    if (platform === 'linux') {
      assert.equal(h.enabled.has('bgos-watcher'), false)
      assert.equal(fs.exists(`${OWNER.linux.home}/.config/systemd/user/bgos-watcher.service`), false)
    }
    // Never two watchers from this HOME at once, at any step.
    for (const snap of h.timeline) assert.ok((snap.running[k(OWNER[platform].bundleDir)] ?? 0) <= 1, `${snap.cmd}: ${JSON.stringify(snap.running)}`)
    // Windows and Linux register the new name BEFORE the old one goes: never a moment without one.
    if (platform !== 'darwin') {
      for (const snap of h.timeline) assert.ok((snap.registrations[k(OWNER[platform].bundleDir)] ?? []).length >= 1, `${snap.cmd}: ${JSON.stringify(snap.registrations)}`)
    }
  })
}

