// -- refuse to replace or delete a registration that records another HOME ----------------------

for (const platform of ['win32', 'darwin', 'linux'] as const) {
  test(`${platform}: a registration under this HOME's own name that records ANOTHER HOME is refused, never replaced or removed`, async () => {
    const { fs, h } = host(platform)
    const s = spec(platform, OWNER[platform])
    // Same name, other HOME (a hash collision, or a registration written by hand).
    if (platform === 'win32') {
      h.tasks.set(s.label, { description: `HOAI per-machine watcher, installed from home=${SCRATCH.win32.home}`, action: `wscript.exe //B "${SCRATCH.win32.bundleDir}\\run-hidden.vbs"`, state: 'Ready' })
    } else if (platform === 'darwin') {
      h.seed.launchd(`${SCRATCH.darwin.home}/Library/LaunchAgents/${s.label}.plist`, legacyPlist(SCRATCH.darwin).replace('<string>ai.bgos.watcher</string>', `<string>${s.label}</string>`))
    } else {
      // The manager reads the owner's unit dir only, so the foreign record is a unit file there that names another HOME.
      h.seed.unit(s.label, legacyUnit(SCRATCH.linux))
    }
    const before = JSON.stringify({ t: [...h.tasks], l: [...h.launchd], e: [...h.enabled], a: [...h.active] })
    const installed = await installWatcherService(s, { exec: h.exec, fs, sleep })
    assert.equal(installed.ok, false)
    assert.match(installed.message, /another HOME/)
    assert.equal(JSON.stringify({ t: [...h.tasks], l: [...h.launchd], e: [...h.enabled], a: [...h.active] }), before)
    const removed = await uninstallWatcherService(s, { exec: h.exec, fs })
    assert.equal(removed.ok, false)
    assert.match(removed.message, /another HOME/)
    assert.equal(JSON.stringify({ t: [...h.tasks], l: [...h.launchd], e: [...h.enabled], a: [...h.active] }), before)
  })
}

