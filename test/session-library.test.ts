// ── Caps and cleaning ───────────────────────────────────────────────────────

test('title, preview and branch are one clean line, capped at the contract limits', () => {
  const long = 'word '.repeat(100)
  const { sessions } = list(
    one(
      transcript(
        customTitle(`  Two\nlines\u0007 and\ta \u202etab   ${long}`),
        lastPrompt(`${'p'.repeat(SESSION_PREVIEW_MAX - 1)}\u{1F600}tail`),
        assistant('x', { gitBranch: `feat/${'b'.repeat(100)}` }),
      ),
    ),
  )
  const row = sessions[0]!
  assert.ok(row.title.startsWith('Two lines and a tab word word'), row.title)
  assert.ok(Array.from(row.title).length <= SESSION_TITLE_MAX)
  assert.doesNotMatch(row.title, /[\u0000-\u001f\u007f\u202e]/)
  assert.equal(row.title, row.title.trim())
  // Capped in characters, and an emoji at the edge is never cut in half.
  assert.equal(Array.from(row.preview!).length, SESSION_PREVIEW_MAX)
  assert.ok(row.preview!.endsWith('\u{1F600}'))
  assert.equal(Array.from(row.branch!).length, SESSION_BRANCH_MAX)
})

