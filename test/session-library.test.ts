const FAKE_TOKEN = ['ghp', '_', 'A1b2C3d4E5f6G7h8I9j0K1l2'].join('')

interface FakeFile {
  text: string
  mtimeMs: number
  unreadable?: boolean
  statFails?: boolean
  folder?: boolean
}

interface Reads {
  head: Array<{ name: string; bytes: number }>
  tail: Array<{ name: string; bytes: number }>
}

/** An in memory agent folder. Paths are matched by their last segment, so
 *  the library's own join() on Windows or POSIX reaches the same file. */
function fakeFs(files: Record<string, FakeFile>): SessionLibraryFs & { reads: Reads } {
  const reads: Reads = { head: [], tail: [] }
  const name = (p: string): string => p.split(/[\\/]/).pop() ?? ''
  const get = (p: string): FakeFile => {
    const f = files[name(p)]
    if (!f) throw new Error(`ENOENT: ${p}`)
    return f
  }
  return {
    reads,
    list: (dir: string) => {
      assert.equal(dir, DIR, 'the library lists the folder it was given')
      return Object.keys(files)
    },
    stat: (p: string) => {
      const f = get(p)
      if (f.statFails) throw new Error(`EPERM: ${p}`)
      return { mtimeMs: f.mtimeMs, size: Buffer.byteLength(f.text), isFile: f.folder !== true }
    },
    readHead: (p: string, bytes: number) => {
      const f = get(p)
      reads.head.push({ name: name(p), bytes })
      if (f.unreadable) throw new Error(`EACCES: ${p}`)
      return Buffer.from(f.text).subarray(0, bytes).toString('utf8')
    },
    readTail: (p: string, bytes: number) => {
      const f = get(p)
      reads.tail.push({ name: name(p), bytes })
      if (f.unreadable) throw new Error(`EACCES: ${p}`)
      const b = Buffer.from(f.text)
      return b.subarray(Math.max(0, b.length - bytes)).toString('utf8')
    },
  }
}

function list(
  files: Record<string, FakeFile>,
  over: { currentName?: string | null; query?: string; limit?: number } = {},
) {
  const fs = fakeFs(files)
  const answer = listAgentSessions({
    projectDir: DIR,
    currentName: over.currentName ?? null,
    query: over.query,
    limit: over.limit ?? SESSIONS_LIST_MAX,
    list: fs.list,
    stat: fs.stat,
    readHead: fs.readHead,
    readTail: fs.readTail,
  })
  return { ...answer, reads: fs.reads }
}

const T0 = Date.parse('2026-09-25T08:00:00.000Z')
const one = (text: string, mtimeMs = T0): Record<string, FakeFile> => ({
  [file(1)]: { text, mtimeMs },
})

