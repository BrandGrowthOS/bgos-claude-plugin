test('on disk: newest first, a large file read at both ends, and a missing folder lists nothing', () => {
  const dir = mkdtempSync(join(tmpdir(), 'session-library-'))
  writeFileSync(join(dir, file(1)), transcript(channel('Older work')))
  const big = transcript(
    channel('Big session'),
    ...Array.from({ length: 16 }, (_, i) => assistant(`filler ${i} ${'z'.repeat(10_000)}`)),
    customTitle('Named at the end'),
  )
  writeFileSync(join(dir, file(2)), big)
  writeFileSync(join(dir, 'README.md'), 'not a session')
  utimesSync(join(dir, file(1)), new Date(T0 - 60_000), new Date(T0 - 60_000))
  utimesSync(join(dir, file(2)), new Date(T0), new Date(T0))

  const library = new AgentSessionLibrary({ projectDir: dir, currentName: () => file(2) })
  const { sessions, truncated } = library.list({ limit: 50 })
  assert.deepEqual(
    sessions.map((r) => [r.id, r.title, r.current]),
    [
      [sid(2), 'Named at the end', true],
      [sid(1), 'Older work', false],
    ],
  )
  assert.equal(sessions[0]!.lastActivityAt, new Date(T0).toISOString())
  assert.equal(truncated, false)

  const missing = new AgentSessionLibrary({ projectDir: join(dir, 'no-such-folder'), currentName: () => null })
  assert.deepEqual(missing.list({ limit: 50 }), { sessions: [], truncated: false })
})

