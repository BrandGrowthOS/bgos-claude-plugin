// ── The read bound ──────────────────────────────────────────────────────────

test(`only the ${SESSION_SCAN_MAX} newest transcripts are ever read, and past them the answer says truncated`, () => {
  assert.equal(SESSION_SCAN_MAX, 200)
  const files: Record<string, FakeFile> = {}
  for (let i = 1; i <= 205; i++) files[file(i)] = { text: transcript(customTitle(`S${i}`)), mtimeMs: T0 - i }
  const searched = list(files, { query: 'no session has this title' })
  assert.equal(searched.sessions.length, 0)
  assert.equal(searched.truncated, true)
  const read = new Set(searched.reads.head.map((r) => r.name))
  assert.equal(read.size, 200)
  for (let i = 201; i <= 205; i++) assert.ok(!read.has(file(i)), `${file(i)} is past the bound`)
})

test('without a query the scan stops one row past the cap', () => {
  const files: Record<string, FakeFile> = {}
  for (let i = 1; i <= 60; i++) files[file(i)] = { text: transcript(customTitle(`S${i}`)), mtimeMs: T0 - i }
  const { reads } = list(files, { limit: 10 })
  assert.equal(reads.head.length, 11)
})

test('each large transcript is read as its first and last 64 KB, never whole', () => {
  assert.equal(SESSION_READ_BYTES, 64 * 1024)
  const filler = (n: number): string[] =>
    Array.from({ length: n }, (_, i) => assistant(`filler ${i} ${'z'.repeat(10_000)}`))
  const text = transcript(
    aiTitle('From the head'),
    ...filler(8),
    customTitle('From the middle, never read'),
    ...filler(8),
    lastPrompt('From the tail'),
  )
  assert.ok(Buffer.byteLength(text) > 2 * SESSION_READ_BYTES + 20_000)
  const { sessions, reads } = list(one(text))
  assert.equal(sessions[0]!.title, 'From the head')
  assert.equal(sessions[0]!.preview, 'From the tail')
  assert.deepEqual(reads.head, [{ name: file(1), bytes: SESSION_READ_BYTES }])
  assert.deepEqual(reads.tail, [{ name: file(1), bytes: SESSION_READ_BYTES }])
})

test('a small transcript is read once, whole', () => {
  const text = transcript(channel('Hello'), customTitle('Small'))
  const { sessions, reads } = list(one(text))
  assert.equal(sessions[0]!.title, 'Small')
  assert.deepEqual(reads.head, [{ name: file(1), bytes: Buffer.byteLength(text) }])
  assert.deepEqual(reads.tail, [])
})

