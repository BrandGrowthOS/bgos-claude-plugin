// ── The cache ───────────────────────────────────────────────────────────────

test('an unchanged transcript is not read again, and a changed mtime or size reads it again', () => {
  const files: Record<string, FakeFile> = {
    [file(1)]: { text: transcript(customTitle('One')), mtimeMs: T0 },
    [file(2)]: { text: transcript(customTitle('Two')), mtimeMs: T0 - 1 },
  }
  const fs = fakeFs(files)
  const library = new AgentSessionLibrary({ projectDir: DIR, currentName: () => null, fs })

  assert.deepEqual(
    library.list({ limit: 50 }).sessions.map((r) => r.title),
    ['One', 'Two'],
  )
  assert.equal(fs.reads.head.length, 2)

  library.list({ limit: 50 })
  library.list({ query: 'one', limit: 50 })
  assert.equal(fs.reads.head.length, 2, 'unchanged files are served from the cache')

  files[file(1)]!.mtimeMs = T0 + 10
  files[file(1)]!.text = transcript(customTitle('One, renamed'))
  assert.equal(library.list({ limit: 50 }).sessions[0]!.title, 'One, renamed')
  assert.deepEqual(
    fs.reads.head.slice(2).map((r) => r.name),
    [file(1)],
  )

  // Same mtime, different size: read again too.
  files[file(2)]!.text = transcript(customTitle('Two, longer now'))
  assert.equal(library.list({ limit: 50 }).sessions[1]!.title, 'Two, longer now')
  assert.deepEqual(
    fs.reads.head.slice(3).map((r) => r.name),
    [file(2)],
  )
})

