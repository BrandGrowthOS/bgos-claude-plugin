/** A session id the way Claude Code mints them (a UUID). */
function sid(n: number): string {
  const s = String(n)
  return `${s.padStart(8, '0')}-1111-4222-8333-${s.padStart(12, '0')}`
}
const file = (n: number): string => `${sid(n)}.jsonl`

const line = (o: unknown): string => JSON.stringify(o)
const transcript = (...lines: string[]): string => `${lines.join('\n')}\n`

const customTitle = (t: string): string =>
  line({ type: 'custom-title', customTitle: t, sessionId: 's' })
const aiTitle = (t: string): string => line({ type: 'ai-title', aiTitle: t, sessionId: 's' })
const lastPrompt = (t: string): string =>
  line({ type: 'last-prompt', lastPrompt: t, leafUuid: 'l', sessionId: 's' })
/** The CLI also writes last-prompt entries with no lastPrompt at all. */
const lastPromptBare = (): string => line({ type: 'last-prompt', leafUuid: 'l', sessionId: 's' })

/** Typed in the terminal by the owner. */
const typed = (text: string, extra: Record<string, unknown> = {}): string =>
  line({
    type: 'user',
    isSidechain: false,
    promptId: 'p',
    origin: { kind: 'human' },
    message: { role: 'user', content: text },
    ...extra,
  })

/** A HOAI channel message, as the CLI records it (isMeta, origin channel). */
function channel(body: string, attrs: Record<string, string> = {}): string {
  const extra = Object.entries(attrs)
    .map(([k, v]) => ` ${k}="${v}"`)
    .join('')
  return line({
    type: 'user',
    isMeta: true,
    isSidechain: false,
    promptId: 'p',
    origin: { kind: 'channel', server: 'plugin:hoai:bgos' },
    message: {
      role: 'user',
      content:
        `<channel source="plugin:hoai:bgos" chat_id="12" message_id="7" user="Kc" ` +
        `user_id="3" assistant_id="901" ts="2026-09-25T08:00:00.000Z" transport="ws" ` +
        `is_shared_recipient="false"${extra}>\n${body}\n</channel>`,
    },
  })
}

