/**
 * The Sessions library, Claude Code side (P6 stage 3, C-32, spec 5.7): the
 * sessions in this agent's own folder, listed for the app's Sessions sheet.
 *
 * What the owner reads in that sheet came from THEIR computer, and some of it
 * was typed in a terminal and never passed through HOAI, so these tests pin
 * three things before anything else:
 *
 * 1. The title is the right one: the owner's own name for the session
 *    (custom-title), else Claude Code's (ai-title), else the first thing the
 *    owner said, with the HOAI channel envelope taken off and never a tool
 *    result, a harness line, a peer or a system message.
 * 2. A title or preview that holds a secret is withheld WHOLE, never masked
 *    and never searched (D24).
 * 3. The read is bounded: the 200 newest top level transcripts at most, the
 *    first and last 64 KB of each, and an unchanged file is not read again.
 *
 * Fixture lines mirror the real entry shapes of a Claude Code 2.1.x
 * transcript on this machine (read by entry type and key names only).
 */

